import { create } from 'zustand'

// Окно первого знакомства на экране «Путь» («С чего начать» + вопрос про календарь).
//
// Общий стор нужен из-за тура: он тоже стартует сам при первом входе, и без этой связки
// у нового ученика оба окна всплывали разом — тур поверх окна, ровно та каша, от которой
// мы и уходим. Тур ждёт, пока человек ответит.
export const useIntroStore = create((set) => ({
  open: false,
  setOpen: (open) => set({ open }),
}))
