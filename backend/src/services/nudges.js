// Хвосты — отдельный повод: ученик занимался, но что-то отложил. Напоминаем
// мягко и не чаще раза в день, иначе это превращается в упрёк.
const TAILS = [
  (n, k) => withName(n, `остались отложенные задания (${k}). Закроем? 🎯`, `Остались отложенные задания (${k}). Закроем? 🎯`),
  (n, k) => withName(n, `у тебя ${k} в хвостах — пара минут, и чисто ✨`, `У тебя ${k} в хвостах — пара минут, и чисто ✨`),
]

export function pickTailsNudge(name, count, index = 0) {
  return {
    title: '🎯 Хвосты ждут',
    body: TAILS[Math.abs(index) % TAILS.length](name, count),
  }
}

const DONE = [
  (n) => withName(n, 'урок пройден! Закрепим? Повторение — половина успеха ✨', 'Урок пройден! Закрепим? Повторение — половина успеха ✨'),
  (n) => withName(n, 'отличная работа! Закрепи знания — повтори пройденное 🔁', 'Отличная работа! Закрепи знания — повтори пройденное 🔁'),
  (n) => withName(n, 'ты молодец! Хочешь закрепить и повторить старый урок? 💡', 'Ты молодец! Хочешь закрепить и повторить старый урок? 💡'),
]

// index — порядковый номер сообщения за день: тексты идут по кругу, а не повторяются
export function pickNudge(name, index = 0, done = false) {
  const list = done ? DONE : TODO
  const body = list[Math.abs(index) % list.length](name)
  return {
    title: done ? '✨ Закрепим знания' : '📚 Время учиться',
    body,
  }
}
