// «Пульс» — мотивационные напоминания в течение дня, пока ученик не позанимался.
//
// Просьба Павла: «каждые 2 часа какие-то мотивационные сообщения с обращением
// к пользователю, пока не пройдёшь урок; прошёл — предлагать закрепить».
//
// Рамки поставлены сознательно: до восьми пушей в день — верный способ добиться того,
// что уведомления отключат совсем, и канал потеряется весь. Поэтому окно 9–21 по времени
// САМОГО ученика, интервал два часа и не больше четырёх сообщений за день.
// Позанимался — до вечера тишина.

export const NUDGE_WINDOW = { from: 9, to: 21 }   // локальные часы ученика
export const NUDGE_INTERVAL_MIN = 120             // два часа между сообщениями
export const NUDGE_MAX_PER_DAY = 4

export function shouldNudge({ localMinutes, lastNudgeMinutes, countToday = 0, studiedToday = false }) {
  if (studiedToday) return false                                   // сегодня уже занимался
  if (countToday >= NUDGE_MAX_PER_DAY) return false
  if (localMinutes < NUDGE_WINDOW.from * 60) return false          // ещё спит
  if (localMinutes >= NUDGE_WINDOW.to * 60) return false           // вечер, хватит
  if (lastNudgeMinutes != null && localMinutes - lastNudgeMinutes < NUDGE_INTERVAL_MIN) return false
  return true
}

export function firstName(fullName) {
  return String(fullName || '').trim().split(/\s+/)[0] || ''
}

