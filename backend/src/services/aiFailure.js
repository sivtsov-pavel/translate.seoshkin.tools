// Отказ ИИ-провайдера словами, а не «не удалось разобрать фото».
//
// Причина отказа почти всегда одна из трёх, и лечатся они по-разному: кончился
// баланс (пополнить), провайдер придержал запросы (подождать), фото правда не
// читается (переснять). Один текст на все три заставляет человека переснимать
// фото, пока не надоест, — а снимок ни при чём (жалоба Павла 29.09.2026).
//
// Код (ai_quota / ai_busy / ai_failed) — машинный и не зависит от языка: по нему
// экран показывает СВОЙ перевод. Текст здесь запасной, на случай незнакомого кода.
//
// Модуль намеренно без единого импорта: это путь ошибки, попасть в него трудно,
// и проверять его надо не поднимая базу и не ходя в сеть.

export function aiFailure(e) {
  const haystack = `${e?.message || ''} ${e?.code || ''} ${e?.error?.code || ''} ${e?.type || ''}`
  if (/insufficient_quota|no credits remaining|credit_balance_exhausted|billing/i.test(haystack)) {
    return {
      status: 503,
      body: { code: 'ai_quota', error: 'Разбор фото временно недоступен: на ИИ-ключе закончился баланс. Фото в порядке — попробуйте позже.' },
    }
  }
  // Порядок важен: у исчерпанного баланса статус тоже 429, и проверка квоты
  // обязана стоять ПЕРЕД проверкой на перегрузку — иначе человеку советуют
  // «подождать минуту» там, где ждать бесполезно.
  if (e?.status === 429 || /rate.?limit|overloaded/i.test(haystack)) {
    return { status: 503, body: { code: 'ai_busy', error: 'ИИ сейчас перегружен. Подождите минуту и попробуйте снова.' } }
  }
  return {
    status: 500,
    body: { code: 'ai_failed', error: 'Не удалось разобрать фото. Попробуйте снять ровнее и при хорошем свете.' },
  }
}
