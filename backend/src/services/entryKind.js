// Что на самом деле распознала камера в строке: слово, предложение или заготовку из учебника.
//
// Vision честно возвращает всё, что видит на странице, и в список «слов» попадает разное:
//   «Welche Sprache sprichst du?»   — целое предложение;
//   «ich suche die ... Straße.»     — упражнение из учебника с многоточием;
//   «_ig»                            — суффикс из грамматической таблицы.
// Если такое подтвердить как слово, оно уходит в словарь ученика и обрастает карточкой,
// диктантом и «Добавь букву» — которые для предложения бессмысленны. Раньше учитель
// вычищал это галочками вручную по всему списку из двух сотен строк.
//
// Предложения не выбрасываем: они ценнее слов. Реальная фраза со страницы — главный
// источник для «Заполни пропуск» и «Напиши предложение», поэтому такие строки уходят
// в раздел предложений, а не в мусор.

// Многоточие в задании учебника: «ich suche die ... Straße» — это не слово и не готовая
// фраза, вписывать туда должен ученик.
const HAS_GAP = /\.{3}|…|_{2,}/

// Личное местоимение в начале строки — признак предложения, а не словарной единицы.
// Длина такое не ловит: «ich heiße Pablo» — три слова, но это предложение, и карточка
// с диктантом ему не нужны. Языки те же, что поддерживает приложение.
const PERSONAL_PRONOUN_START = /^(ich|du|er|sie|es|wir|ihr|i|you|he|she|we|they|yo|tú|él|ella|nosotros|ellos)$/i

/**
 * @returns {'sentence'|'fragment'|'word'}
 *   sentence — строку надо предложить как предложение урока;
 *   fragment — обрывок/суффикс/заготовка: в словарь не годится, галочка снята;
 *   word     — обычная словарная единица.
 */
export function classifyEntry(raw) {
  const text = String(raw || '').trim()
  if (!text) return 'fragment'

  // Суффикс или окончание из грамматической таблицы: «_ig», «-chen», «…lich».
  if (/^[-_–—…]/.test(text) || /[-_]$/.test(text)) return 'fragment'

  const words = text.split(/\s+/).filter(Boolean)

  // Пропуск для ученика — заготовка задания, а не материал.
  if (HAS_GAP.test(text)) return words.length >= 3 ? 'sentence' : 'fragment'

  // Вопрос или восклицание — всегда фраза, даже короткая («Wie geht's?»).
  if (/[?!]$/.test(text) && words.length >= 2) return 'sentence'

  // Точка в конце при нескольких словах: «Ich wohne hier.»
  if (/\.$/.test(text) && words.length >= 3) return 'sentence'

  // Длинная связка слов — предложение и без знака в конце: vision часто теряет точку.
  // Порог 4: устойчивые выражения («noch nicht», «zu Hause», «guten Tag») остаются словами,
  // а «Kannst du mir helfen» — уже фраза.
  if (words.length >= 4) return 'sentence'

  // Короткое предложение из двух-трёх слов порог длины не ловит: «ich heiße Pablo»
  // проходило как слово и получало карточку с диктантом. Признак надёжнее длины —
  // личное местоимение в начале: где есть подлежащее, там предложение.
  if (words.length >= 2 && PERSONAL_PRONOUN_START.test(words[0])) return 'sentence'

  return 'word'
}

// Склейка строк, разорванных переносом в тетради.
//
// Распознавание отдаёт каждую строку рукописи отдельно, и предложение, не поместившееся
// в ширину страницы, приходит двумя обрывками. Из-за этого «Die Dose ist leer» в базе
// лежало как «die Dose» — а такой обрывок уже не годится ни в упражнение, ни в словарь.
//
// Склеиваем в двух случаях:
//  • строка кончается дефисом — это явный перенос слова, части соединяем БЕЗ пробела;
//  • строка не закончена по смыслу (нет точки, вопроса, восклицания), а следующая
//    начинается со строчной буквы — продолжение той же фразы.
export function joinWrappedLines(lines) {
  const out = []
  for (const raw of (lines || [])) {
    const text = String(typeof raw === 'string' ? raw : raw?.text || '').trim()
    if (!text) continue
    const prev = out[out.length - 1]
    if (prev) {
      // Перенос слова: «Kühl-» + «schrank» → «Kühlschrank».
      if (/[-‑–]$/.test(prev)) {
        out[out.length - 1] = prev.replace(/[-‑–]$/, '') + text.replace(/^[-‑–]\s*/, '')
        continue
      }
      // Незаконченная фраза + продолжение со строчной.
      if (!/[.!?:;]$/.test(prev) && /^\p{Ll}/u.test(text)) {
        out[out.length - 1] = `${prev} ${text}`
        continue
      }
    }
    out.push(text)
  }
  return out
}
