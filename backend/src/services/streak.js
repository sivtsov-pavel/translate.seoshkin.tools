// Серия — сколько дней подряд человек занимался.
//
// Счёт жил в проекте дважды: в дашборде (routes/exercises.js) и на экране «Путь»
// (routes/path.js). Версии разошлись, и та, что на главной у новичка, считала неверно:
//
//   for (const row of days) {
//     if (diff === streak || (streak === 0 && diff === 1)) streak++
//     else break
//   }
//
// Пока сегодняшний день есть в списке, всё сходилось: diff идёт 0, 1, 2… и streak за ним.
// Но если сегодня ещё не занимались, первая итерация попадала в особый случай
// (streak === 0 && diff === 1) и ставила streak = 1 — а следующий день давал diff = 2 при
// streak = 1, и цикл обрывался. То есть серия схлопывалась до единицы у любого, кто открыл
// приложение утром: Павел занимался 29 и 30 сентября, а главная 1 октября показывала «1».
//
// Для человека это выглядит ровно как «мои занятия не засчитались» — то же, на что он
// жаловался про упражнения. Поэтому счёт теперь один на оба экрана.
//
// Правило: серия считается от сегодняшнего дня, а если сегодня ещё не занимались — от
// вчерашнего (день не закончился, рано рвать серию). Пропуск в середине обрывает счёт.

const DAY = 86400000

/**
 * @param {Array<Date|string|number>} days — дни занятий, по убыванию, без повторов
 * @param {Date} [now] — «сегодня» (для тестов)
 * @returns {number} дней подряд
 */
export function computeStreak(days, now = new Date()) {
  if (!days?.length) return 0
  const midnight = (v) => { const d = new Date(v); d.setUTCHours(0, 0, 0, 0); return d.getTime() }
  const today = midnight(now)
  // Чужой порядок и повторы не должны влиять на ответ: приводим вход к канону сами.
  const uniq = [...new Set(days.map(midnight))].sort((a, b) => b - a)

  let streak = 0
  let expect = null
  for (const d of uniq) {
    const diff = Math.round((today - d) / DAY)
    if (diff < 0) continue              // будущее (часовые пояса) — не считаем и не рвём
    if (expect === null) {
      if (diff > 1) return 0            // последний день занятий раньше вчера — серия оборвана
      expect = diff                     // старт: сегодня, иначе вчера
    }
    if (diff !== expect) break          // пропуск в середине
    streak++
    expect++
  }
  return streak
}
