-- Расписание «по умолчанию»: пометка, что календарь ученику никто не выбирал.
--
-- Раньше курс без расписания стоял ЗАКРЫТЫМ целиком, а объяснение «выбери календарь»
-- жило только в баннере полного интерфейса. Новичок его не видел вовсе: заходил,
-- упирался в запертую дорогу и шёл спрашивать учителя (жалоба Павла 05.09.2026,
-- «мне приходится каждому объяснять»).
--
-- Теперь расписание заводится само — все семь дней, старт сегодня, — и человек
-- начинает учиться сразу. Флаг ниже отличает такой автокалендарь от осознанно
-- выбранного: пока он TRUE, приложение один раз предлагает выбрать свои дни.
-- Сбрасывается в FALSE и при выборе своих дней, и при ответе «оставить каждый день» —
-- то есть означает ровно «человека ещё не спрашивали».
ALTER TABLE course_schedules ADD COLUMN IF NOT EXISTS is_default BOOLEAN NOT NULL DEFAULT FALSE;
