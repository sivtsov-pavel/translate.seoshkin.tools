-- Одно слово — одно упражнение каждого типа.
--
-- Баг Павла от 22.08.2026: «почему разное количество упражнений? 59/59, 0/63, 0/66».
-- Знаменатель у каждого типа был свой, потому что генератор вставлял всё, что вернула
-- модель, не проверяя, есть ли уже упражнение для этой пары (слово, тип). В уроке 19
-- у «backen» набралось четыре «вставь слово» и по три «выбери ответ» / «вставь букву»,
-- а по всем немецким урокам — 412 лишних упражнений.
--
-- Код теперь везде вставляет с ON CONFLICT DO NOTHING, а этот индекс — барьер на уровне
-- базы: он действует и для разовых скриптов, и для любого будущего пути вставки.
-- Упражнения без слова (word_id IS NULL) индекс не трогает — они чинятся отдельно.
CREATE UNIQUE INDEX IF NOT EXISTS idx_exercises_word_type_unique
  ON exercises (lesson_id, word_id, type) WHERE word_id IS NOT NULL;
