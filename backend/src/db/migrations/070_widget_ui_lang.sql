-- Язык интерфейса для виджета.
--
-- В токене уже лежит target_lang — какой язык человек УЧИТ (по нему выбираются уроки).
-- Но варианты ответа и подписи на виджете нужны на языке, на котором человек ЧИТАЕТ:
-- испанец, учащий немецкий, должен видеть «hermana», а не «сестра». Это разные вещи,
-- и одной колонкой они не покрываются.
--
-- Отдельной миграцией, а не правкой 069: та уже применена на проде и повторно не выполнится.
ALTER TABLE widget_tokens ADD COLUMN IF NOT EXISTS ui_lang TEXT NOT NULL DEFAULT 'ru';
