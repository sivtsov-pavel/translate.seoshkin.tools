-- Карточка на экране блокировки: включена или нет.
--
-- Раньше флаг жил только в самом телефоне, а веб-настройки передавали его односторонне
-- (intent://). Из-за этого настройки не знали реального состояния: кнопка показывала
-- «Выключить» там, где уведомление было выключено, и нажатие гасило то, чего нет.
--
-- Теперь источник правды — сервер: настройки читают состояние, виджет получает его
-- вместе с обычным ответом и приводит телефон в соответствие.
ALTER TABLE widget_tokens ADD COLUMN IF NOT EXISTS notify_on BOOLEAN NOT NULL DEFAULT FALSE;
