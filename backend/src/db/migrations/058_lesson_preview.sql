--
-- Раньше превью существовало только в HTTP-ответе. Разбор идёт секунды на страницу,
-- и на мобильной связи запрос успевает оборваться: браузер показывает «failed to fetch»,
-- а работа уже сделана и оплачена. Повторить нельзя — фото помечены обработанными,
-- и второй вызов возвращает пустой список. Учитель терял и разбор, и деньги за него.
--
-- Теперь превью лежит здесь до подтверждения: страницу можно перезагрузить, вернуться
-- позже, продолжить с телефона — список слов на месте.
