-- Переводы примера-предложения на локали интерфейса.
--
-- До этого перевод примера жил в одной колонке example_sentence_ru — только
-- по-русски. Во флеш-карточке под немецкой фразой турок, араб и албанец видели
-- русскую строку: для них это не перевод, а шум. Русский остаётся в своей
-- колонке (на него смотрит половина кода и все прежние скрипты), а остальные
-- девять языков ложатся сюда — так же, как words.translations для самого слова.
ALTER TABLE words ADD COLUMN IF NOT EXISTS example_translations JSONB DEFAULT '{}'::jsonb;
