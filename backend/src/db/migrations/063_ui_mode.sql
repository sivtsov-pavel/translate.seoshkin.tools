-- Режим интерфейса: «новичок» (Путь — одна дорога, один следующий шаг) или «эксперт»
-- (полный интерфейс со всеми разделами).
--
-- NULL = не выбран явно, и тогда режим определяется ролью: учителю эксперт, ученику
-- новичок. Так учитель, ни разу не трогавший тумблер, видит привычный интерфейс,
-- а новый ученик сразу попадает в простой.
--
-- ВАЖНО: режим переключает ТОЛЬКО отображение. Права на бэкенде остаются прежними —
-- иначе «режим ученика» стал бы дырой в доступе к чужим данным.
ALTER TABLE user_settings ADD COLUMN IF NOT EXISTS ui_mode VARCHAR(8)
  CHECK (ui_mode IS NULL OR ui_mode IN ('novice', 'expert'));
